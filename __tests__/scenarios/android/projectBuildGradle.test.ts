import * as fs from 'fs';
import { modifyProjectBuildGradleForGoogleServices } from '../../../plugin/src/android/withProjectGoogleServices';
import { getFixturePath } from '../../utils';

const baseline = fs.readFileSync(
  getFixturePath('android', 'project_build.gradle'),
  'utf8'
);

describe('android scenarios — modifyProjectBuildGradleForGoogleServices', () => {
  it('injects the Google Services classpath into buildscript.dependencies', () => {
    expect(modifyProjectBuildGradleForGoogleServices(baseline))
      .toMatchInlineSnapshot(`
      "// Top-level build file where you can add configuration options common to all sub-projects/modules.

      buildscript {
          repositories {
              google()
              mavenCentral()
          }
          dependencies {
              classpath "com.google.gms:google-services:4.4.0"  // Google Services plugin
              classpath('com.android.tools.build:gradle')
          }
      }

      allprojects {
          repositories {
              google()
              mavenCentral()
          }
      }
      "
    `);
  });

  it('is idempotent', () => {
    const once = modifyProjectBuildGradleForGoogleServices(baseline);
    const twice = modifyProjectBuildGradleForGoogleServices(once);
    expect(twice).toEqual(once);
  });

  // Incremental prebuild of a project generated by plugin releases that injected 4.3.13: the
  // line is updated in place, so the project keeps exactly one Customer.io classpath line.
  it('updates the line an earlier plugin version injected instead of adding another', () => {
    const generatedByOlderPlugin = modifyProjectBuildGradleForGoogleServices(
      baseline
    ).replace('google-services:4.4.0', 'google-services:4.3.13');

    const updated = modifyProjectBuildGradleForGoogleServices(
      generatedByOlderPlugin
    );

    expect(updated).toEqual(modifyProjectBuildGradleForGoogleServices(baseline));
    expect(updated.match(/com\.google\.gms:google-services:/g)).toHaveLength(1);
  });

  // A customer's own declaration is not ours to rewrite. Gradle resolves the highest declared
  // version, so a newer customer pin wins and an older one is raised to this plugin's floor.
  it('leaves a google-services classpath the customer declared alone', () => {
    const withCustomerPin = baseline.replace(
      "classpath('com.android.tools.build:gradle')",
      "classpath('com.android.tools.build:gradle')\n        classpath('com.google.gms:google-services:4.4.2')"
    );

    const updated = modifyProjectBuildGradleForGoogleServices(withCustomerPin);

    expect(updated).toContain("classpath('com.google.gms:google-services:4.4.2')");
    expect(updated).toContain(
      'classpath "com.google.gms:google-services:4.4.0"  // Google Services plugin'
    );
  });

  // Negative-template: customer's project build.gradle doesn't have a buildscript+dependencies
  // block. Helper should leave the file untouched.
  it('returns input unchanged when there is no buildscript+dependencies block', () => {
    const noBuildscript = [
      'allprojects {',
      '    repositories {',
      '        google()',
      '    }',
      '}',
      '',
    ].join('\n');
    expect(modifyProjectBuildGradleForGoogleServices(noBuildscript)).toEqual(
      noBuildscript
    );
  });
});
